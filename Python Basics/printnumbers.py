# Print Numbers 
# You can also use the print() function to display numbers:

# Print on the same line
print(5, end=" ")
print(30000, end=" ")
print(50000, end= "")

# Print numbers
print(5)
print(30000)        
print(50000)

# Print the sum of two numbers
print(5 + 10)
print(7 * 3)
print(10 / 2)
print(10 - 4)

