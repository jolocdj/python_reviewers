# Output Variables
# The Python print() function is used to output data to the standard output device (screen).

x = "Jolo is cute!"
print(x)

# In the print() function, you output multiple variables, separated by a comma:

x = "Jolo is cute!"
y = "Yaya Dub is beautiful!"  

print(x, end=" ")
print(y)
# Notice the space character after "Python " and "is ", without them the result would be "Pythonisawesome".

x = "Python "
y = "is "
z = "awesome!"

print(x, end="")
print(y, end="")
print(z)
